"""Generate src/tables.rs from Unikey's data.cpp (ukengine, Pham Kim Long).

Usage:
    uv run --no-project python generate_tables.py <path to data.cpp> <path to tables.rs>

data.cpp is not valid UTF-8 (legacy charset bytes inside char literals), so it
is parsed as bytes.
"""

import re
import sys

TOTAL_CHARACTERS = 213

TOKEN_PATTERN = re.compile(rb"'(.)'|(0[xX][0-9a-fA-F]+)|([{}])", re.DOTALL)
BLOCK_COMMENT_PATTERN = re.compile(rb"/\*.*?\*/", re.DOTALL)
LINE_COMMENT_PATTERN = re.compile(rb"//[^\n]*")

SINGLE_BYTE_NAMES = ["TCVN3", "VPS", "VISCII", "BK_HCM_1", "VIETWARE_F", "ISC"]
DOUBLE_BYTE_NAMES = ["VNI_WINDOWS", "BK_HCM_2", "VIETWARE_X", "VNI_MAC"]


def strip_comments(source: bytes) -> bytes:
    without_blocks = BLOCK_COMMENT_PATTERN.sub(b"", source)
    return LINE_COMMENT_PATTERN.sub(b"", without_blocks)


def parse_initializer(source: bytes, name: bytes):
    """Return the nested list of numbers that initializes the array `name`."""
    declaration_start = source.index(name + b"[")
    equals_position = source.index(b"=", declaration_start)
    tokens = list(TOKEN_PATTERN.finditer(source, equals_position))
    position = 0

    def parse_block():
        nonlocal position
        assert tokens[position].group(3) == b"{"
        position += 1
        items = []
        while True:
            token = tokens[position]
            if token.group(3) == b"}":
                position += 1
                return items
            if token.group(3) == b"{":
                items.append(parse_block())
                continue
            if token.group(1) is not None:
                items.append(token.group(1)[0])
            else:
                items.append(int(token.group(2), 16))
            position += 1

    return parse_block()


def format_array(values, width, indent="    "):
    lines = []
    for start in range(0, len(values), 12):
        row = ", ".join(f"0x{value:0{width}X}" for value in values[start : start + 12])
        lines.append(f"{indent}{row},")
    return "\n".join(lines)


def emit_table_group(lines, constant_prefix, names, element_type, tables, width):
    for name, table in zip(names, tables):
        assert len(table) == TOTAL_CHARACTERS, (name, len(table))
        lines.append(f"pub const {constant_prefix}_{name}: [{element_type}; STANDARD_CHARACTER_COUNT] = [")
        lines.append(format_array(table, width))
        lines.append("];")
        lines.append("")


def emit_single_table(lines, constant_name, element_type, table, width):
    assert len(table) == TOTAL_CHARACTERS, (constant_name, len(table))
    lines.append(f"pub const {constant_name}: [{element_type}; STANDARD_CHARACTER_COUNT] = [")
    lines.append(format_array(table, width))
    lines.append("];")
    lines.append("")


def main():
    data_path, output_path = sys.argv[1], sys.argv[2]
    with open(data_path, "rb") as data_file:
        source = strip_comments(data_file.read())

    single_byte_tables = parse_initializer(source, b"SingleByteTables")
    double_byte_tables = parse_initializer(source, b"DoubleByteTables")
    assert len(single_byte_tables) == len(SINGLE_BYTE_NAMES)
    assert len(double_byte_tables) == len(DOUBLE_BYTE_NAMES)

    lines = [
        "//! Generated by tools/generate_tables.py from Unikey ukengine data.cpp",
        "//! (Copyleft 1998-2004 Pham Kim Long, GPL-2.0-or-later). Do not edit by hand.",
        "//!",
        "//! Every table has one entry per standard Vietnamese character; see lib.rs.",
        "",
        "pub const STANDARD_CHARACTER_COUNT: usize = 213;",
        "",
    ]
    emit_table_group(lines, "SINGLE_BYTE", SINGLE_BYTE_NAMES, "u8", single_byte_tables, 2)
    emit_table_group(lines, "DOUBLE_BYTE", DOUBLE_BYTE_NAMES, "u16", double_byte_tables, 4)
    emit_single_table(lines, "WIN_CP1258_COMPOSITE", "u16", parse_initializer(source, b"WinCP1258"), 4)
    emit_single_table(lines, "WIN_CP1258_PRECOMPOSED", "u16", parse_initializer(source, b"WinCP1258Pre"), 4)
    emit_single_table(lines, "UNICODE_PRECOMPOSED", "u16", parse_initializer(source, b"UnicodeTable"), 4)
    emit_single_table(lines, "VIQR", "u32", parse_initializer(source, b"VIQRTable"), 8)
    emit_single_table(lines, "UNICODE_DECOMPOSED", "u32", parse_initializer(source, b"UnicodeComposite"), 8)

    with open(output_path, "w", encoding="utf-8", newline="\n") as output_file:
        output_file.write("\n".join(lines))


if __name__ == "__main__":
    main()
