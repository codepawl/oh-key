/// `lowercase_word` must already be lowercase ASCII.
pub(crate) fn is_doubled_key_word(lowercase_word: &[u8]) -> bool {
    DOUBLED_KEY_WORDS
        .binary_search_by(|candidate| candidate.as_bytes().cmp(lowercase_word))
        .is_ok()
}

